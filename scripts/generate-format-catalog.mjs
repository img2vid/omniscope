import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const records = [];
const validExt = ext => ext && !/[\s/\\*?\[\]{}]/u.test(ext) && !ext.startsWith('.') && !ext.endsWith('.');
const normalize = extensions => [...new Set((extensions ?? []).map(e => e.replace(/^\./, '').toLowerCase()).filter(validExt))];

for (const language of read('data/format-sources/linguist.json')) {
  const ext = normalize(language.extensions);
  const filenames = [...new Set(language.filenames ?? [])].filter(n => n && !/[\\/]/.test(n));
  if (!ext.length && !filenames.length) continue;
  const xml = language.name === 'XML';
  const json = language.name === 'JSON';
  const markdown = language.name === 'Markdown';
  records.push({
    ext, ...(filenames.length ? { filenames } : {}), name: language.name,
    cat: language.type === 'programming' ? 'code' : language.type === 'prose' ? 'text' : 'data',
    viewer: xml ? 'xml' : json ? 'json' : markdown ? 'markdown' : 'code',
    mime: xml ? 'application/xml' : json ? 'application/json' : 'text/plain',
    source: 'github-linguist', reading: 'text', textOnly: true,
    desc: `Documented by GitHub Linguist; ${json || xml ? 'structured text' : 'source text'} reader.`,
  });
}

// Only exact MIME aliases of implemented decoders get binary readers. A name or
// a vendor prefix is never evidence that a proprietary format is decodable.
const decoders = new Map([
  ['application/pdf', ['pdf', 'document']],
  ['application/zip', ['archive', 'archive']],
  ['application/gzip', ['archive', 'archive']],
  ['application/x-tar', ['archive', 'archive']],
  ['message/rfc822', ['eml', 'email']],
  ['image/jpeg', ['image', 'image']], ['image/png', ['image', 'image']],
  ['image/gif', ['image', 'image']], ['image/webp', ['image', 'image']],
  ['image/bmp', ['image', 'image']], ['image/avif', ['image', 'image']],
  ['audio/midi', ['midi', 'audio']], ['audio/wav', ['audio', 'audio']],
  ['audio/mpeg', ['audio', 'audio']], ['audio/flac', ['audio', 'audio']],
  ['font/ttf', ['font', 'font']], ['font/otf', ['font', 'font']],
]);
for (const [mime, item] of Object.entries(read('data/format-sources/mime-db.json'))) {
  const ext = normalize(item.extensions);
  if (!ext.length) continue;
  const text = mime.startsWith('text/') || /[+/](?:json|xml)$/.test(mime) ||
    ['application/javascript', 'application/yaml', 'application/toml', 'application/x-sh', 'application/x-httpd-php'].includes(mime);
  const [viewer, cat] = text
    ? [/[+/]json$/.test(mime) ? 'json' : /[+/]xml$/.test(mime) ? 'xml' : 'code', 'data']
    : decoders.get(mime) ?? ['fallback', mime.startsWith('image/') ? 'image' : mime.startsWith('audio/') ? 'audio' : mime.startsWith('video/') ? 'video' : 'binary'];
  const reading = text ? 'text' : viewer === 'fallback' ? 'inspect' : 'decoded';
  records.push({ ext, name: mime, mime, cat, viewer, source: 'mime-db', reading,
    ...(text ? { textOnly: true } : {}),
    desc: reading === 'inspect'
      ? 'Documented MIME extension; byte inspection only. No format-specific decoder is installed.'
      : `Documented MIME extension; ${reading === 'text' ? 'text' : 'compatible format'} reader.`,
  });
}

const snapshots = ['data/format-sources/linguist.json', 'data/format-sources/mime-db.json'];
const hashes = Object.fromEntries(snapshots.map(path => [path, createHash('sha256').update(readFileSync(new URL(path, root))).digest('hex')]));
const chunks = [];
for (let i = 0; i < records.length; i += 100) chunks.push(records.slice(i, i + 100));
const generated = '// Generated by scripts/generate-format-catalog.mjs; do not edit.\n' +
  '// Sources and licenses: data/format-sources/sources.json, third_party/.\n' +
  'import type { RawFormat } from "@/lib/types";\n\n' +
  // Bound contextual array inference so TypeScript does not build a union of
  // thousands of different literal object shapes (TS2590).
  chunks.map((chunk, i) => `const CHUNK_${i}: RawFormat[] = [\n` + chunk.map(r => '  ' + JSON.stringify(r) + ',').join('\n') + '\n];\n').join('\n') +
  '\nexport const SOURCED_FORMATS: RawFormat[] = [\n  ' + chunks.map((_, i) => `...CHUNK_${i}`).join(',\n  ') + '\n];\n';
const outputs = new Map([
  ['src/lib/formats/sourced-formats.ts', generated],
  ['data/format-sources/snapshot-hashes.json', JSON.stringify(hashes, null, 2) + '\n'],
]);
for (const [path, content] of outputs) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== content) throw new Error(`Stale generated file: ${fileURLToPath(url)}`);
  } else writeFileSync(url, content);
}
console.log(`${records.length} source records; ${process.argv.includes('--check') ? 'generated files verified' : 'catalog generated'}.`);
